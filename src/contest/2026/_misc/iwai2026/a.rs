// 問題文と制約は読みましたか？
// #[fastout]
fn main() {
    input! {
        xs: [i64; 7],
    }

    let ans = (1..=7)
        .map(|i| {
            //
            let can_solve_all = xs[..i].iter().copied().all(|x| x != -1);
            if can_solve_all {
                let sum: i64 = xs[..i].iter().sum();
                let remain = 6000 - sum;
                if remain < 0 { -1 } else { remain }
            } else {
                -1
            }
        })
        .collect_vec();
    print_vec(&ans);
}

