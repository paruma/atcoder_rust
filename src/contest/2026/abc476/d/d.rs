fn main() {
    input! {
        n: usize,
        m: usize,
        k: i64,
        x: i64,
        y: i64,
        mut a_s: [i64; n],
        mut b_s: [i64; m],
    }

    a_s.sort();
    b_s.sort();

    let mut rem_y = y;
    let mut money = x + y * k;

    // 0個の場合
    let cuma = CumSum::new(&a_s);

    let mut ans = cuma.max_right(0, |sum| sum <= money);

    // lg!(rem_y);

    // lg!(money);
    // lg!(ans);

    for i in 0..m {
        let need_y = num_integer::div_ceil(b_s[i], k);
        if rem_y >= need_y {
            rem_y -= need_y;
            money -= b_s[i];
            let sub_ans = cuma.max_right(0, |sum| sum <= money) + (i + 1);
            ans = ans.max(sub_ans);
            // lg!(rem_y);
            // lg!(money);
            // lg!(ans);
        } else {
            break;
        }
    }

    println!("{}", ans);
}

